#!/bin/bash
# Builds MoltenVK (the version in the crossover-sources tarball) as an x86_64 dylib into the
# engine's dist folder, so Wine can be configured --with-vulkan and DXVK has a Vulkan driver.
#
# The sources are compiled directly instead of through the Xcode projects: those need
# glslang, SPIRV-Tools and other repositories fetched and built first, and none of that is
# needed for what Wine and DXVK use. Two things are left out as a result:
#   - GLSL shader input (MoltenVK's own extension; DXVK only ever passes SPIR-V), replaced by
#     the small stub in moltenvk-stubs/;
#   - SPIRV-Tools disassembly in debug logs (MVK_EXCLUDE_SPIRV_TOOLS).
# Header-only dependencies at the revisions MoltenVK pins are taken from engine/downloads/.
# Usage: engine/build-moltenvk.sh
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
source "$HERE/env.sh"
M="$SRC/moltenvk"
B="$HERE/build-deps/moltenvk"
JOBS="$(sysctl -n hw.ncpu)"
VH_REV="$(cat "$M/ExternalRevisions/Vulkan-Headers_repo_revision")"
CE_REV="$(cat "$M/ExternalRevisions/cereal_repo_revision")"
VH_TGZ="$HERE/downloads/vulkan-headers-$VH_REV.tar.gz"
CE_TGZ="$HERE/downloads/cereal-$CE_REV.tar.gz"
for f in "$VH_TGZ" "$CE_TGZ"; do [ -f "$f" ] || { echo "missing $f" >&2; exit 1; }; done

rm -rf "$B" && mkdir -p "$B/obj" "$B/vulkan-headers" "$B/cereal" "$B/gen" "$B/inc"
tar -xzf "$VH_TGZ" -C "$B/vulkan-headers" --strip-components=1
tar -xzf "$CE_TGZ" -C "$B/cereal" --strip-components=1
{
    echo "// Generated by build-moltenvk.sh"
    echo "static const char* mvkRevString = \"crossover-sources-26.3.0\";"
} > "$B/gen/mvkGitRevDerived.h"
# <MoltenVK/...> headers without touching the source tree's own (dangling) include symlinks.
ln -s "$M/MoltenVK/MoltenVK/API" "$B/inc/MoltenVK"

INC=(-I"$B/gen" -I"$B/inc" -I"$B/vulkan-headers/include" -I"$B/cereal/include"
     -I"$M/Common" -I"$M/MoltenVKShaderConverter" -I"$M/External/SPIRV-Cross" -I"$M/External")
while IFS= read -r d; do INC+=(-I"$d"); done < <(find "$M/MoltenVK/MoltenVK" -type d)

DEFS=(-DNDEBUG=1 -DSPIRV_CROSS_NAMESPACE_OVERRIDE=MVK_spirv_cross -DMVK_FRAMEWORK_VERSION=1.2.10
      -DMVK_EXCLUDE_SPIRV_TOOLS=1)
FLAGS=(-arch x86_64 -mmacosx-version-min=10.15 -O2 -g0 -fvisibility=hidden -fvisibility-inlines-hidden
       -fno-objc-arc -w)

{
    find "$M/MoltenVK/MoltenVK" "$M/Common" \( -name '*.mm' -o -name '*.m' -o -name '*.cpp' -o -name '*.c' \)
    for f in SPIRVToMSLConverter.cpp SPIRVSupport.cpp SPIRVConversion.mm FileSupport.mm; do
        echo "$M/MoltenVKShaderConverter/MoltenVKShaderConverter/$f"
    done
    for f in spirv_cfg spirv_cross spirv_cross_parsed_ir spirv_cross_util spirv_glsl spirv_msl spirv_parser spirv_reflect; do
        echo "$M/External/SPIRV-Cross/$f.cpp"
    done
    echo "$HERE/moltenvk-stubs/GLSLToSPIRVConverterStub.cpp"
} > "$B/sources.txt"
echo "==> compiling $(wc -l < "$B/sources.txt" | tr -d ' ') files"

compile() {
    local src="$1" obj lang
    obj="$B/obj/$(echo "${src#"$SRC"/}" | tr '/ ' '__').o"
    # (a plain string, not an array: bash 3.2 with `set -u` rejects expanding an empty array)
    case "$src" in
        *.cpp|*.mm) lang="-std=c++17 -stdlib=libc++" ;;
        *)          lang="-x objective-c" ;;
    esac
    clang++ "${FLAGS[@]}" $lang "${DEFS[@]}" "${INC[@]}" \
        -c "$src" -o "$obj" 2>> "$B/compile.err" || { echo "FAILED $src" >> "$B/failed.txt"; return 1; }
}
: > "$B/compile.err"; rm -f "$B/failed.txt"
running=0
while IFS= read -r src; do
    compile "$src" &
    running=$((running + 1))
    if [ "$running" -ge "$JOBS" ]; then wait -n 2>/dev/null || wait; running=$((running - 1)); fi
done < "$B/sources.txt"
wait || true
if [ -f "$B/failed.txt" ]; then cat "$B/failed.txt"; echo "see $B/compile.err" >&2; exit 1; fi

echo "==> linking"
clang++ -arch x86_64 -mmacosx-version-min=10.15 -dynamiclib -o "$B/libMoltenVK.dylib" "$B"/obj/*.o \
    -install_name "@rpath/libMoltenVK.dylib" -stdlib=libc++ \
    -framework Metal -framework Foundation -framework QuartzCore -framework CoreGraphics \
    -framework IOKit -framework IOSurface -framework AppKit

mkdir -p "$DIST/lib" "$DIST/include"
cp "$B/libMoltenVK.dylib" "$DIST/lib/libMoltenVK.dylib"
# Headers Wine's configure looks for.
rm -rf "$DIST/include/vulkan" "$DIST/include/vk_video" "$DIST/include/MoltenVK"
cp -R "$B/vulkan-headers/include/vulkan" "$B/vulkan-headers/include/vk_video" "$DIST/include/"
cp -R "$M/MoltenVK/MoltenVK/API" "$DIST/include/MoltenVK"

echo "==> result"
file "$DIST/lib/libMoltenVK.dylib" | cut -c1-140
nm -gU "$DIST/lib/libMoltenVK.dylib" | grep -c " T _vk" | sed 's/^/exported vk* functions: /'
